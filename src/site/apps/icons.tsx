type IconProps = {size?: number; color?: string; style?: CSSProperties};
const pathOf = (svg: string) => svg.match(/ d="([^"]+)"/)![1];
const symbol = (svg: string, initial: number, tint?: string) => {
  const d = pathOf(svg);
  return ({size = initial, color = tint, style}: IconProps) => (
    <svg width={size} height={size} viewBox="0 -960 960 960" aria-hidden="true" style={{display: 'block', ...style}}><path d={d} fill={color ?? 'currentColor'} /></svg>
  );
};

